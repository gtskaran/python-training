#python comparison operators
#boolean opertors
"""
==  Equal to
!=  Not Equal
>   Greater than
<   Less than
>=  Greater than or equal to
<=  Less than or equal to
"""
print("== Comparison Operators ==")
val1 = 45
val2 = 38
print(f"Values are val1 = {val1}, val2 = {val2}")
print(f"Equal to Comparison val1 == val2 is {val1 == val2}")
print(f"Not Equal to Comparison val1 != val2 is {val1 != val2}")
print(f"Greater than Comparison val1 > val2 is {val1 > val2}")
print(f"Greater than or Equal to Comparison val1 >= val2 is {val1 >= val2}")
print(f"Less than Comparison val1 < val2 is {val1 < val2}")
print(f"Less than or Equal to Comparison val1 <= val2 is {val1 <= val2}")

