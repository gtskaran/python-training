#bitwise operators
#bitwise and (&)
#bitwise or (|)
#bitwise xor (^)
#bitwise complement (~)
#left shift (<<)
#right shift (>>)
print("===Bitwise Operators===")
print(f"Binary of 12 = {bin(12)}")
print(f"Binary of 14 = {bin(14)}")
print(f"Bitwise AND (&) 12 & 14 = {12 & 14}")
print(f"Bitwise OR (|) 12 | 14 = {12 | 14}")
print(f"Bitwise XOR (^) 12 ^ 14 = {12 ^ 14}")
print(f"Bitwise Complement (~) ~12 = {~12}")
print(f"Bitwise left shift (<<) 12 << 2 = {12 << 2}")
print(f"Bitwise right shift (>>) 12 >> 2 = {12 >> 2}")
