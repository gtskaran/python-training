#python assignment operators
# = is used for assignment
# variable = experssion/value
#(expression get evaluated first and assigned to variable)
# combine operators
# arithmetic and bitwise operators can be combined
# if the variable used both sides
a = 10
print("===Assignment Operators===")
print(f"value of a is {a}")
# a = a + 5
a += 5
print(f"value of a is {a}")
a -= 5
print(f"value of a is {a}")
a *= 5
print(f"value of a is {a}")
a ^= 5
print(f"value of a is {a}")

